export function isKnownIndianState(value: string): value is IndianState {
  return (INDIAN_STATES as readonly string[]).includes(value);
}

export function getLocationSuggestionsForState(state: string): string[] {
  const trimmed = state.trim();
  if (!trimmed) return [];

  if (isKnownIndianState(trimmed)) {
    return CITIES_BY_STATE[trimmed];
  }

  const matchedState = INDIAN_STATES.find(
    (item) =>
      item.toLowerCase() === trimmed.toLowerCase() ||
      STATE_DISPLAY_LABELS[item].toLowerCase() === trimmed.toLowerCase()
  );

  return matchedState ? CITIES_BY_STATE[matchedState] : [];
}

export function resolveIndianState(value: string): IndianState | null {
  const trimmed = value.trim();
  if (!trimmed) return null;

  if (isKnownIndianState(trimmed)) return trimmed;

  return (
    INDIAN_STATES.find(
      (item) =>
        item.toLowerCase() === trimmed.toLowerCase() ||
        STATE_DISPLAY_LABELS[item].toLowerCase() === trimmed.toLowerCase()
    ) ?? null
  );
}
